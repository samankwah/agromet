// Helper function to get translated text
export const getTranslation = (key, language = "en", category = "phrases") => {
  const translations = ghanaianLanguages[category];
  if (
    !translations ||
    !translations[language] ||
    !translations[language][key]
  ) {
    // Fallback to English if translation not found
    return translations?.en?.[key] || key;
  }
  return translations[language][key];
};

// Helper function to get language info
export const getLanguageInfo = (langCode) => {
  return (
    ghanaianLanguages.languages[langCode] || ghanaianLanguages.languages.en
  );
};

// Helper function to get all supported languages (main 5 only)
export const getSupportedLanguages = () => {
  const mainLanguages = ["en", "tw", "gaa", "ee", "dag"];
  const result = {};
  mainLanguages
    .filter((code) => ghanaianLanguages.languages[code])
    .forEach((code) => {
      result[code] = ghanaianLanguages.languages[code];
    });
  return result;
};

